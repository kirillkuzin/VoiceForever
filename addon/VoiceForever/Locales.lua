local source = locales.enUS
local strings = locales[GetLocale and GetLocale() or "enUS"] or source

-- L.key is the string in the client's language; T(key, ...) also fills in the values.
ns.L = setmetatable({}, {
    __index = function(_, key)
        return strings[key] or source[key] or key
    end,
})
ns.T = function(key, ...)
    if select("#", ...) > 0 then
        return string.format(ns.L[key], ...)
    end
    return ns.L[key]
end
ns.locales = locales -- for the tests
